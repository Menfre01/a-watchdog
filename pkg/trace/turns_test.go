// textMsg 构造一条只含文本的消息。
func textMsg(role, text string) MainlineMessage {
	return MainlineMessage{Role: role, Blocks: []MainlineBlock{{"type": "text", "text": text}}}
}

// resultMsg 构造一条只含工具结果的消息(迭代产物,非新输入)。
func resultMsg(text string) MainlineMessage {
	return MainlineMessage{Role: "user", Blocks: []MainlineBlock{
		{"type": "tool_result", "tool_use_id": "t1", "content": text},
	}}
}

// turnSteps 断言分组结果与期望的 step 序列一致。
func assertTurns(t *testing.T, got []Turn, want [][]int64) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("轮次数 = %d, want %d(%+v)", len(got), len(want), got)
	}
	for i, w := range want {
		if strings.Join(seqStrings(got[i].StepSeqs), ",") != strings.Join(seqStrings(w), ",") {
			t.Errorf("第 %d 轮 steps = %v, want %v", i+1, got[i].StepSeqs, w)
		}
	}
}

// seqStrings 把序号序列转为字符串(便于比较)。
func seqStrings(seqs []int64) []string {
	out := make([]string, 0, len(seqs))
	for _, s := range seqs {
		out = append(out, strconv.FormatInt(s, 10))
	}
	return out
}

// TestGroupTurnsMultiStep 覆盖多步轮次合并:工具迭代留在同一轮。
func TestGroupTurnsMultiStep(t *testing.T) {
	steps := []StepForTurn{
		{Seq: 1, Delta: Delta{Kind: DeltaNew}, Added: []MainlineMessage{textMsg("user", "帮我看看")}},
		{Seq: 2, Delta: Delta{Kind: DeltaAdded}, Added: []MainlineMessage{
			assistantCalls(use("t1", "Read", "{}")), resultMsg("body"),
		}},
		{Seq: 3, Delta: Delta{Kind: DeltaAdded}, Added: []MainlineMessage{
			assistantCalls(use("t2", "Bash", "{}")), resultMsg("done"),
		}},
	}
	got := GroupTurns(steps)
	assertTurns(t, got, [][]int64{{1, 2, 3}})
}

// TestGroupTurnsNewInputOpensTurn 覆盖新用户输入开启新轮次。
