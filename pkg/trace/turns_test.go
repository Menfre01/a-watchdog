// TestIsHumanInput 覆盖「人的新输入」判定边界。
func TestIsHumanInput(t *testing.T) {
	cases := []struct {
		name string
		msg  MainlineMessage
		want bool
	}{
		{"纯文本 user", textMsg("user", "继续"), true},
		{"带 tool_result 的 user", resultMsg("body"), false},
		{"工具结果 + 文本混合", MainlineMessage{Role: "user", Blocks: []MainlineBlock{
			{"type": "tool_result", "tool_use_id": "t1", "content": "x"},
			{"type": "text", "text": "继续"},
		}}, false},
		{"注入文本", textMsg("user", "<system-reminder>hi</system-reminder>"), false},
		{"前导空白的注入文本", textMsg("user", "  \n<system-reminder>hi</system-reminder>"), false},
		{"assistant 文本", textMsg("assistant", "好的"), false},
		// 无文本的 user 消息不构成可读的新输入(反例:空块、纯图片、空白文本)。
		{"空块消息", MainlineMessage{Role: "user"}, false},
		{"空白文本", textMsg("user", "   \n  "), false},
		{"通用标签注入", textMsg("user", "<custom-tag>x</custom-tag>"), false},
		{"闭标签注入", textMsg("user", "</session>"), false},
		{"尖括号但非标签", textMsg("user", "< 3 表示小于"), true},
		{"首个文本为空次个非空", MainlineMessage{Role: "user", Blocks: []MainlineBlock{
			{"type": "text", "text": ""},
			{"type": "text", "text": "真正的问题"},
		}}, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := isHumanInput(tc.msg); got != tc.want {
				t.Errorf("isHumanInput() = %v, want %v", got, tc.want)
			}
		})
	}
}
