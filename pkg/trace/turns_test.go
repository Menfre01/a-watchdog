// TestGroupTurnsChainIsolated 覆盖无重合步的隔离:不与主链轮次混合。
func TestGroupTurnsChainIsolated(t *testing.T) {
	steps := []StepForTurn{
		{Seq: 1, Delta: Delta{Kind: DeltaNew}, Added: []MainlineMessage{textMsg("user", "主任务")}},
		{Seq: 2, Delta: Delta{Kind: DeltaAdded}, Added: []MainlineMessage{resultMsg("ok")}},
		{Seq: 3, Delta: Delta{Kind: DeltaChain}, Added: []MainlineMessage{textMsg("user", "(子任务)")}},
		{Seq: 4, Delta: Delta{Kind: DeltaAdded}, Added: []MainlineMessage{resultMsg("sub done")}},
	}
	got := GroupTurns(steps)
	assertTurns(t, got, [][]int64{{1, 2}, {3, 4}})
	if !got[1].Parallel {
		t.Errorf("无重合步所在轮次未标记平行链: %+v", got[1])
	}
	if got[0].Parallel {
		t.Errorf("主链轮次被误标为平行链: %+v", got[0])
	}
}

// TestGroupTurnsAgentMessageKeepsTurn 覆盖子 agent 结果的注入:
// harness 在子 agent 完成时注入「Another Claude session sent a message」,
// 它是**发起该子 agent 那一轮的延续**,不得开启新轮次(真实流量形态)。
func TestGroupTurnsAgentMessageKeepsTurn(t *testing.T) {
	steps := []StepForTurn{
		{Seq: 1, Delta: Delta{Kind: DeltaNew}, Added: []MainlineMessage{
			textMsg("user", "来个子 agent 探索一下这个 project"),
		}},
		{Seq: 2, Delta: Delta{Kind: DeltaAdded}, Added: []MainlineMessage{
			assistantCalls(use("t1", "Agent", "{}")),
		}},
		{Seq: 3, Delta: Delta{Kind: DeltaAdded}, Added: []MainlineMessage{
			textMsg("user", "Another Claude session sent a message:\n<agent-message from=\"a8c8712990\">结果</agent-message>"),
		}},
		{Seq: 4, Delta: Delta{Kind: DeltaAdded}, Added: []MainlineMessage{
			textMsg("user", "<system-reminder>\n[SYSTEM NOTIFICATION - NOT USER INPUT]\nThis is an automated"),
		}},
	}
	// 全部并入同一轮:这里是 harness 注入,不是用户的新诉求。
	assertTurns(t, GroupTurns(steps), [][]int64{{1, 2, 3, 4}})
}

// TestGroupTurnsSideFollowsNextMainStep 覆盖旁路步的归属:
// 它应跟随后续的主路步,而不是被并入前一轮。
// 真实流量:用户第二问(seq 3)与一次监控(seq 2)同为 09:05:50,归错会把
// 监控放进上一轮。
func TestGroupTurnsSideFollowsNextMainStep(t *testing.T) {
	steps := []StepForTurn{
		{Seq: 1, Delta: Delta{Kind: DeltaNew}, Added: []MainlineMessage{textMsg("user", "第一问")}},
		{Seq: 2, Delta: Delta{Kind: DeltaNew}, Side: true, Added: []MainlineMessage{textMsg("user", "(监控)")}},
		{Seq: 3, Delta: Delta{Kind: DeltaAdded}, Added: []MainlineMessage{textMsg("user", "第二问")}},
		{Seq: 4, Delta: Delta{Kind: DeltaNew}, Side: true, Added: []MainlineMessage{textMsg("user", "(监控)")}},
		{Seq: 5, Delta: Delta{Kind: DeltaAdded}, Added: []MainlineMessage{resultMsg("ok")}},
	}
	turns := GroupTurns(steps)
	// seq 2 跟随 seq 3(第二轮);seq 4 跟随 seq 5(仍在第二轮)。
	assertTurns(t, turns, [][]int64{{1}, {2, 3, 4, 5}})
}

